export class ReviewResultPageComponent implements OnInit {
  private readonly route = inject(ActivatedRoute);
  private readonly http = inject(HttpClient);
  readonly ws = inject(WorkspaceService);

  readonly reviewData = signal<any | null>(null);

  ngOnInit(): void {
    const routeId = this.route.snapshot.paramMap.get('id');
    const cachedResult = this.ws.activeReviewResult();

    if (cachedResult && (!routeId || cachedResult.id === routeId)) {
      this.reviewData.set(cachedResult);
    } else if (routeId) {
      this.http.get<any>(`http://localhost:4000/reviews/${routeId}`).subscribe({
        next: (data) => {
          this.reviewData.set(data?.review || data);
        },
        error: (err) => {
          this.reviewData.set({
            status: 'FAILED',
            summary: err?.error?.message || 'Failed to retrieve code review details.',
            files: [],
          });
        },
      });
    } else {
      this.reviewData.set(cachedResult);
    }
  }

  getScore(review: any): number {
    if (typeof review?.score === 'number') return review.score;
    return 0;
  }

  getScoreColor(score: number): string {
    if (score >= 90) return '#10b981';
    if (score >= 70) return '#f59e0b';
    return '#ef4444';
  }

  getAllIssues(review: any): any[] {
    if (!review || !review.files) return [];
    const issues: any[] = [];
    for (const f of review.files) {
      if (f.issues && Array.isArray(f.issues)) {
        for (const i of f.issues) {
          issues.push({ ...i, filename: f.filename });
        }
      }
    }
    return issues;
  }

  countIssuesByCat(review: any, category: string): number {
    const issues = this.getAllIssues(review);
    return issues.filter((i) => (i.category || '').toUpperCase().includes(category)).length;
  }

  exportReport(format: 'markdown' | 'pdf'): void {
    const review = this.reviewData();
    if (review?.id) {
      this.ws.exportReport(format);
    }
  }
}
